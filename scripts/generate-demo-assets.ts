/**
 * Renders the bundled example's images with Playwright and embeds them in
 * src/lib/demo/assets.ts so the example works with no network access.
 *
 *   npm run assets:demo
 */
import { chromium } from "playwright";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

type Asset = { name: string; width: number; height: number; html: string };

const base = `
  * { box-sizing: border-box; margin: 0; }
  body { font-family: "Segoe UI", system-ui, sans-serif; overflow: hidden; }
`;

const hero = (title: string, sub: string, from: string, to: string, tag: string) => `
<style>${base}
  .wrap { width: 100vw; height: 100vh; background: linear-gradient(135deg, ${from}, ${to}); color: #fff;
    display: flex; flex-direction: column; justify-content: center; padding: 0 88px; position: relative; }
  .tag { font-size: 26px; letter-spacing: .14em; text-transform: uppercase; opacity: .85; margin-bottom: 22px; }
  h1 { font-size: 92px; line-height: 1.02; font-weight: 800; max-width: 760px; }
  p { font-size: 32px; margin-top: 26px; opacity: .92; max-width: 640px; }
  .card { position: absolute; right: 70px; top: 110px; width: 300px; height: 410px; border-radius: 28px;
    background: rgba(255,255,255,.95); box-shadow: 0 30px 60px rgba(0,0,0,.25); transform: rotate(6deg); padding: 34px; }
  .line { height: 16px; border-radius: 8px; background: #d9dde5; margin-bottom: 18px; }
  .line.a { width: 80%; background: ${from}; opacity: .7; } .line.b { width: 60%; } .line.c { width: 90%; }
  .dot { position: absolute; border-radius: 50%; background: rgba(255,255,255,.14); }
  .edge { position: absolute; inset: 0; border: 6px dashed rgba(255,255,255,.35); pointer-events: none; }
</style>
<div class="wrap">
  <div class="dot" style="width:420px;height:420px;left:-140px;bottom:-200px"></div>
  <div class="dot" style="width:220px;height:220px;right:380px;top:-90px"></div>
  <div class="tag">${tag}</div>
  <h1>${title}</h1>
  <p>${sub}</p>
  <div class="card"><div class="line a"></div><div class="line b"></div><div class="line c"></div><div class="line b"></div><div class="line c"></div><div class="line a"></div></div>
  <div class="edge"></div>
</div>`;

const assets: Asset[] = [
  {
    name: "hero-a.jpg",
    width: 1200,
    height: 630,
    html: hero("Fieldnote 2", "Notes that organize themselves.", "#2f6fdf", "#7b4ce0", "Spring launch · og:image"),
  },
  {
    name: "hero-b.jpg",
    width: 1200,
    height: 630,
    html: hero("Plan less. Ship more.", "Variant B landing page artwork.", "#0f8f6f", "#2b6cb0", "Variant B · og:image"),
  },
  {
    name: "x-card.jpg",
    width: 1200,
    height: 600,
    html: hero("40% off for early birds", "Ends Sunday — X-specific artwork.", "#111827", "#d9480f", "twitter:image"),
  },
  {
    name: "square.png",
    width: 1080,
    height: 1080,
    html: `<style>${base}
      .s { width:100vw;height:100vh;display:grid;place-items:center;background:#fdf6e3;color:#1f2937; }
      .s div { text-align:center } .s b { display:block;font-size:150px;font-weight:800;color:#7b4ce0 }
      .s span { font-size:46px } .s i { display:block;font-size:30px;margin-top:30px;color:#6b7280;font-style:normal }</style>
      <div class="s"><div><b>FN2</b><span>Second og:image · square</span><i>1080 × 1080</i></div></div>`,
  },
  {
    name: "touch-icon.png",
    width: 180,
    height: 180,
    html: `<style>${base} .i{width:100vw;height:100vh;background:linear-gradient(135deg,#2f6fdf,#7b4ce0);display:grid;place-items:center;color:#fff;font-size:92px;font-weight:800}</style><div class="i">F</div>`,
  },
  {
    name: "favicon.png",
    width: 32,
    height: 32,
    html: `<style>${base} .i{width:100vw;height:100vh;background:#2f6fdf;border-radius:7px;display:grid;place-items:center;color:#fff;font-size:21px;font-weight:800}</style><div class="i">F</div>`,
  },
];

const browser = await chromium.launch();
const page = await browser.newPage();
const out: Record<string, string> = {};
for (const asset of assets) {
  await page.setViewportSize({ width: asset.width, height: asset.height });
  await page.setContent(asset.html);
  const jpeg = asset.name.endsWith(".jpg");
  const png = await page.screenshot(jpeg ? { type: "jpeg", quality: 86 } : { type: "png" });
  out[asset.name] = png.toString("base64");
  console.log(`${asset.name}: ${asset.width}x${asset.height}, ${Math.round(png.length / 1024)} KB`);
}
await browser.close();

const target = fileURLToPath(new URL("../src/lib/demo/assets.ts", import.meta.url));
const body = Object.entries(out)
  .map(([name, b64]) => `  "${name}": "${b64}",`)
  .join("\n");
writeFileSync(
  target,
  `// Generated by scripts/generate-demo-assets.ts — do not edit by hand.\n` +
    `// Base64 images (PNG/JPEG) for the bundled example site.\n` +
    `export const DEMO_ASSETS: Record<string, string> = {\n${body}\n};\n`,
);
console.log(`wrote ${target}`);
